"""parameters.toml contract between the frontend codec and ChemEx.

``tests/fixtures/parameter_contract/*.toml`` are ChemEx files (the docs example, extended
with bounds). ``emitted/`` holds what the frontend writes after importing them
(regenerated by ``npx vitest run parameterToml.contract -u``).
ChemEx must read both into identical defaults: same parameters, values and bounds.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from chemex.configuration.parameters import read_defaults

FIXTURES = Path(__file__).parent / "fixtures" / "parameter_contract"
SOURCES = sorted(FIXTURES.glob("*.toml"))


def _settings(path: Path) -> dict[str, tuple]:
    out: dict[str, tuple] = {}
    for pname, setting in read_defaults([path]):
        key = f"{pname.section}|{pname.name}|{pname.spin_system}"
        out[key] = (setting.value, setting.min, setting.max, setting.brute_step)
    return out


def test_fixtures_present() -> None:
    assert SOURCES, "no parameter contract fixtures"


@pytest.mark.parametrize("source", SOURCES, ids=lambda p: p.name)
def test_frontend_export_reads_identically_in_chemex(source: Path) -> None:
    emitted = FIXTURES / "emitted" / source.name
    assert emitted.is_file(), f"missing emitted/{source.name}; regenerate the golden file"
    assert _settings(emitted) == _settings(source)


@pytest.mark.parametrize("source", SOURCES, ids=lambda p: p.name)
def test_bounds_reach_chemex(source: Path) -> None:
    settings = _settings(FIXTURES / "emitted" / source.name)
    pb = next(v for k, v in settings.items() if "|PB|" in k)
    kex = next(v for k, v in settings.items() if "|KEX_AB|" in k)
    assert pb[:3] == (0.015, 0.0, 0.2)
    assert kex[:3] == (70.0, 1.0, 1000.0)
